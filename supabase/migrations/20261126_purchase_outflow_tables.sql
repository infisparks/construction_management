-- ============================================================================
-- Purchase Outflow Module: Vendor Quotations & Purchase Requisitions
-- Safe & Idempotent: creates new tables + storage bucket without touching existing data
-- ============================================================================

-- 1. Vendor Quotations & Finalization Table
CREATE TABLE IF NOT EXISTS public.purchase_quotations (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  serial_no BIGINT GENERATED BY DEFAULT AS IDENTITY,
  inquiry_code TEXT,
  project_id UUID REFERENCES public.projects(id) ON DELETE SET NULL,
  heading TEXT NOT NULL,
  description TEXT,
  quotations JSONB NOT NULL DEFAULT '[]'::jsonb,
  status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'finalized', 'closed')),
  created_by_email TEXT,
  is_deleted BOOLEAN NOT NULL DEFAULT false,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_purchase_quotations_active_created
  ON public.purchase_quotations (is_deleted, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_purchase_quotations_project_active
  ON public.purchase_quotations (project_id, is_deleted);

-- 2. Purchase Requisitions & 3-Step Approval Table (flexible JSONB form_data)
CREATE TABLE IF NOT EXISTS public.purchase_requisitions (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  serial_no BIGINT GENERATED BY DEFAULT AS IDENTITY,
  req_code TEXT,
  project_id UUID REFERENCES public.projects(id) ON DELETE SET NULL,
  title TEXT NOT NULL,
  form_data JSONB NOT NULL DEFAULT '{}'::jsonb,
  approval_stage TEXT NOT NULL DEFAULT 'pending_purchase'
    CHECK (approval_stage IN ('pending_purchase', 'pending_director', 'pending_accounts', 'approved', 'rejected')),
  approval_history JSONB NOT NULL DEFAULT '[]'::jsonb,
  submitted_by_email TEXT,
  submitted_by_role TEXT,
  is_deleted BOOLEAN NOT NULL DEFAULT false,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_purchase_requisitions_active_created
  ON public.purchase_requisitions (is_deleted, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_purchase_requisitions_stage_active
  ON public.purchase_requisitions (approval_stage, is_deleted);

-- 3. Enable RLS with authenticated access policies
ALTER TABLE public.purchase_quotations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.purchase_requisitions ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies WHERE tablename = 'purchase_quotations' AND policyname = 'Allow authenticated all on purchase_quotations'
  ) THEN
    CREATE POLICY "Allow authenticated all on purchase_quotations"
      ON public.purchase_quotations FOR ALL TO authenticated USING (true) WITH CHECK (true);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies WHERE tablename = 'purchase_requisitions' AND policyname = 'Allow authenticated all on purchase_requisitions'
  ) THEN
    CREATE POLICY "Allow authenticated all on purchase_requisitions"
      ON public.purchase_requisitions FOR ALL TO authenticated USING (true) WITH CHECK (true);
  END IF;
END $$;

-- 4. Storage Bucket for Purchase Quotations (PDFs & Images)
INSERT INTO storage.buckets (id, name, public)
VALUES ('purchase-documents', 'purchase-documents', true)
ON CONFLICT (id) DO NOTHING;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies WHERE schemaname = 'storage' AND tablename = 'objects' AND policyname = 'Public read purchase-documents'
  ) THEN
    CREATE POLICY "Public read purchase-documents"
      ON storage.objects FOR SELECT USING (bucket_id = 'purchase-documents');
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies WHERE schemaname = 'storage' AND tablename = 'objects' AND policyname = 'Authenticated upload purchase-documents'
  ) THEN
    CREATE POLICY "Authenticated upload purchase-documents"
      ON storage.objects FOR INSERT TO authenticated WITH CHECK (bucket_id = 'purchase-documents');
  END IF;
END $$;
