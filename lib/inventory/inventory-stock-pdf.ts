'use client';

import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import { ConstructionMaterial } from './inventory-types';
import { formatINR, getCleanItemCode } from './inventory-voucher-pdf';

export interface StockSummaryPdfOptions {
  projectName?: string;
  projectCode?: string;
  generatedBy?: string;
}

/**
 * Generate a certified landscape PDF statement for all inventory materials and their current stock balances.
 */
export function generateInventoryStockSummaryPdf(
  materials: ConstructionMaterial[],
  options: StockSummaryPdfOptions = {}
): jsPDF {
  const {
    projectName = 'Noori Crest Tower',
    projectCode = 'NC-2026',
    generatedBy = 'Site Store Incharge',
  } = options;

  const doc = new jsPDF({
    orientation: 'landscape',
    unit: 'mm',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth(); // 297mm
  const pageHeight = doc.internal.pageSize.getHeight(); // 210mm
  const margin = 12;
  let currentY = margin;

  // 1. Top Decorative Brand Accent Strip
  doc.setFillColor(79, 70, 229); // Indigo 600
  doc.rect(0, 0, pageWidth, 5, 'F');

  // 2. Main Header Container
  doc.setFillColor(248, 250, 252); // Slate 50
  doc.rect(margin, currentY, pageWidth - margin * 2, 28, 'F');
  doc.setDrawColor(226, 232, 240); // Slate 200
  doc.rect(margin, currentY, pageWidth - margin * 2, 28, 'S');

  // Left Title & Project Info
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.setTextColor(30, 27, 75); // Deep Indigo
  doc.text('SITE MATERIAL STOCK BALANCE & INVENTORY STATEMENT', margin + 6, currentY + 9);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(100, 116, 139); // Slate 500
  doc.text(
    `Project: ${projectName} (${projectCode})  |  Repository: Live Store Inventory  |  Audited Balance`,
    margin + 6,
    currentY + 16
  );

  doc.setFontSize(8);
  doc.setTextColor(148, 163, 184); // Slate 400
  const generatedDateStr = new Date().toLocaleDateString('en-IN', {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
  });
  const generatedTimeStr = new Date().toLocaleTimeString('en-IN', {
    hour: '2-digit',
    minute: '2-digit',
    hour12: true,
  });
  doc.text(
    `Statement Generated: ${generatedDateStr} at ${generatedTimeStr}  |  Generated By: ${generatedBy}`,
    margin + 6,
    currentY + 22
  );

  // Right Reference Badge
  const docRefNo = `STK-${new Date().getFullYear()}-${Math.floor(1000 + Math.random() * 9000)}`;
  doc.setFillColor(238, 242, 255); // Indigo 50
  doc.roundedRect(pageWidth - margin - 58, currentY + 5, 52, 18, 2, 2, 'FD');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8);
  doc.setTextColor(79, 70, 229);
  doc.text('STATEMENT REF #', pageWidth - margin - 54, currentY + 11);
  doc.setFontSize(10);
  doc.setTextColor(30, 27, 75);
  doc.text(docRefNo, pageWidth - margin - 54, currentY + 18);

  currentY += 32;

  // 3. Quick KPI Summary Metric Bar
  const totalItems = materials.length;
  const inStockCount = materials.filter((m) => m.currentStock > (m.minimumAlertStock || 0)).length;
  const lowStockCount = materials.filter(
    (m) => m.currentStock > 0 && m.currentStock <= (m.minimumAlertStock || 0)
  ).length;
  const depletedCount = materials.filter((m) => m.currentStock <= 0).length;
  const totalValuation = materials.reduce(
    (sum, m) => sum + (m.currentStock || 0) * (m.averageUnitRate || 0),
    0
  );

  const cardWidth = (pageWidth - margin * 2 - 12) / 4;
  const cardHeight = 14;

  const kpis = [
    { label: 'TOTAL SKUs REGISTERED', value: `${totalItems} Items`, color: [67, 56, 202] },
    { label: 'HEALTHY IN-STORE BALANCE', value: `${inStockCount} SKUs`, color: [16, 149, 108] },
    { label: 'LOW STOCK BUFFER ALERTS', value: `${lowStockCount} SKUs`, color: [217, 119, 6] },
    { label: 'DEPLETED / ZERO STOCK', value: `${depletedCount} SKUs`, color: [225, 29, 72] },
  ];

  kpis.forEach((kpi, idx) => {
    const cardX = margin + idx * (cardWidth + 4);
    doc.setFillColor(248, 250, 252);
    doc.setDrawColor(226, 232, 240);
    doc.roundedRect(cardX, currentY, cardWidth, cardHeight, 1.5, 1.5, 'FD');

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(6.5);
    doc.setTextColor(kpi.color[0], kpi.color[1], kpi.color[2]);
    doc.text(kpi.label, cardX + 4, currentY + 5);

    doc.setFontSize(10);
    doc.setTextColor(15, 23, 42);
    doc.text(kpi.value, cardX + 4, currentY + 11);
  });

  currentY += cardHeight + 4;

  // 4. Detailed Stock Inventory Table
  const tableHeaders = [
    [
      'S.No',
      'Item Code',
      'Construction Material & Description',
      'Category',
      'Storage Godown / Shed',
      'Current Stock',
      'Buffer Alert',
      'Avg Unit Rate',
      'Est. Valuation',
      'Status',
    ],
  ];

  const tableRows = materials.map((m, idx) => {
    const cleanCode = getCleanItemCode(m.code, m.id, idx + 1);
    const valuation = (m.currentStock || 0) * (m.averageUnitRate || 0);

    let status = 'In Stock';
    if (m.currentStock <= 0) {
      status = 'Depleted';
    } else if (m.currentStock <= (m.minimumAlertStock || 0)) {
      status = 'Low Stock';
    }

    const rateText =
      m.averageUnitRate && m.averageUnitRate > 0
        ? `Rs. ${Number(m.averageUnitRate).toLocaleString('en-IN')}`
        : 'Set on purchase';

    const valuationText = valuation > 0 ? formatINR(valuation) : 'Rs. 0.00';

    return [
      String(idx + 1),
      cleanCode,
      m.name + (m.description ? ` (${m.description})` : ''),
      m.category || 'General',
      m.storageLocation || 'Central Site Yard',
      `${m.currentStock} ${m.unit || 'Nos'}`,
      `${m.minimumAlertStock || 0} ${m.unit || 'Nos'}`,
      rateText,
      valuationText,
      status,
    ];
  });

  autoTable(doc, {
    startY: currentY,
    head: tableHeaders,
    body: tableRows,
    theme: 'grid',
    styles: {
      font: 'helvetica',
      fontSize: 7.5,
      cellPadding: 2,
      lineColor: [226, 232, 240],
      lineWidth: 0.15,
      textColor: [30, 41, 59],
      valign: 'middle',
    },
    headStyles: {
      fillColor: [49, 46, 129], // Deep Navy Indigo
      textColor: [255, 255, 255],
      fontStyle: 'bold',
      fontSize: 8,
      halign: 'left',
    },
    columnStyles: {
      0: { cellWidth: 10, halign: 'center' }, // S.No
      1: { cellWidth: 20, fontStyle: 'bold' }, // Item Code
      2: { cellWidth: 70 }, // Name
      3: { cellWidth: 32 }, // Category
      4: { cellWidth: 40 }, // Location
      5: { cellWidth: 24, fontStyle: 'bold', halign: 'right' }, // Stock
      6: { cellWidth: 20, halign: 'right' }, // Buffer
      7: { cellWidth: 25, halign: 'right' }, // Avg Rate
      8: { cellWidth: 25, halign: 'right', fontStyle: 'bold' }, // Valuation
      9: { cellWidth: 19, halign: 'center' }, // Status
    },
    alternateRowStyles: {
      fillColor: [248, 250, 252],
    },
    didParseCell: (data) => {
      // Color-code Status column
      if (data.section === 'body' && data.column.index === 9) {
        const val = String(data.cell.raw);
        if (val === 'Depleted') {
          data.cell.styles.textColor = [225, 29, 72]; // Rose 600
          data.cell.styles.fontStyle = 'bold';
        } else if (val === 'Low Stock') {
          data.cell.styles.textColor = [217, 119, 6]; // Amber 600
          data.cell.styles.fontStyle = 'bold';
        } else {
          data.cell.styles.textColor = [16, 149, 108]; // Emerald 600
          data.cell.styles.fontStyle = 'bold';
        }
      }
    },
    margin: { left: margin, right: margin, bottom: 22 },
  });

  // 5. Total Valuation Summary Row & Signature Block on final page
  const totalPages = (doc as any).internal.getNumberOfPages();

  for (let page = 1; page <= totalPages; page++) {
    doc.setPage(page);

    // Bottom Decorative Footer Strip
    doc.setFillColor(241, 245, 249);
    doc.rect(margin, pageHeight - 14, pageWidth - margin * 2, 9, 'F');
    doc.setDrawColor(226, 232, 240);
    doc.rect(margin, pageHeight - 14, pageWidth - margin * 2, 9, 'S');

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.5);
    doc.setTextColor(100, 116, 139);
    doc.text(
      `Armee Enterprises PMS  •  Certified Material Stock Report  •  Total Valuation: ${formatINR(totalValuation)}`,
      margin + 4,
      pageHeight - 8.5
    );

    const pageStr = `Page ${page} of ${totalPages}`;
    doc.text(pageStr, pageWidth - margin - doc.getTextWidth(pageStr) - 4, pageHeight - 8.5);
  }

  return doc;
}

/**
 * Returns a Blob URL for the inventory stock statement PDF.
 */
export function getInventoryStockSummaryPdfBlobUrl(
  materials: ConstructionMaterial[],
  projectName: string = 'Noori Crest Tower'
): { blobUrl: string; doc: jsPDF } {
  const doc = generateInventoryStockSummaryPdf(materials, { projectName });
  const blob = doc.output('blob');
  const blobUrl = URL.createObjectURL(blob);
  return { blobUrl, doc };
}

/**
 * Directly downloads the stock statement PDF file.
 */
export function downloadInventoryStockSummaryPdf(
  materials: ConstructionMaterial[],
  projectName: string = 'Noori Crest Tower'
): void {
  const doc = generateInventoryStockSummaryPdf(materials, { projectName });
  const dateStr = new Date().toISOString().split('T')[0];
  doc.save(`Site_Inventory_Stock_Report_${dateStr}.pdf`);
}

/**
 * Opens the stock statement PDF directly in a new browser tab via Blob URL.
 */
export function viewInventoryStockSummaryPdfInNewTab(
  materials: ConstructionMaterial[],
  projectName: string = 'Noori Crest Tower'
): string {
  const { blobUrl } = getInventoryStockSummaryPdfBlobUrl(materials, projectName);
  if (typeof window !== 'undefined') {
    window.open(blobUrl, '_blank');
  }
  return blobUrl;
}
